import { createFileRoute } from "@tanstack/react-router";
import { useState } from "react";
import { runAI } from "@/lib/ai";

export const Route = createFileRoute("/")({
  head: () => ({
    meta: [
      { title: "Aurum — AI Workplace Productivity Assistant" },
      { name: "description", content: "Generate emails, summarise meeting notes and plan your tasks with AI." },
      { property: "og:title", content: "Aurum — AI Workplace Productivity Assistant" },
      { property: "og:description", content: "Emails, meeting summaries and task plans tailored to your input." },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary" },
    ],
  }),
  component: Index,
});

type Tool = "email" | "notes" | "planner";
const TOOLS: { id: Tool; label: string; icon: string; desc: string }[] = [
  { id: "email", label: "Email Generator", icon: "✉", desc: "Personalised professional emails in your chosen tone." },
  { id: "notes", label: "Notes Summarizer", icon: "≡", desc: "Turn raw meeting notes into decisions, actions and deadlines." },
  { id: "planner", label: "Task Planner", icon: "◷", desc: "A prioritised daily or weekly schedule built from your tasks." },
];

function Index() {
  const [tool, setTool] = useState<Tool>("email");
  const current = TOOLS.find((t) => t.id === tool)!;
  return (
    <div className="flex min-h-screen flex-col md:flex-row">
      <aside className="border-b border-border bg-sidebar md:sticky md:top-0 md:h-screen md:w-64 md:border-b-0 md:border-r">
        <div className="p-5">
          <p className="font-display text-2xl text-gold">Aurum</p>
          <p className="text-xs text-muted-foreground">AI Workplace Assistant</p>
        </div>
        <nav className="flex gap-1 overflow-x-auto px-3 pb-3 md:flex-col">
          {TOOLS.map((t) => (
            <button
              key={t.id}
              onClick={() => setTool(t.id)}
              className={`flex shrink-0 items-center gap-3 rounded-md px-3 py-2 text-left text-sm transition-colors ${
                tool === t.id ? "bg-sidebar-accent text-gold" : "text-muted-foreground hover:bg-sidebar-accent/60 hover:text-foreground"
              }`}
            >
              <span className="w-4 text-center">{t.icon}</span>
              {t.label}
            </button>
          ))}
        </nav>
      </aside>
      <main className="mx-auto w-full max-w-4xl flex-1 p-5 md:p-10">
        <h1 className="font-display text-3xl md:text-4xl">{current.label}</h1>
        <p className="mt-1 text-muted-foreground">{current.desc}</p>
        <div className="mt-8">
          {tool === "email" && <EmailTool />}
          {tool === "notes" && <NotesTool />}
          {tool === "planner" && <PlannerTool />}
        </div>
        <p className="mt-10 rounded-md border border-border bg-card p-4 text-xs text-muted-foreground">
          <span className="text-gold">Responsible AI:</span> Outputs are generated by a free public AI service (Pollinations.ai) and may contain errors.
          Review, edit and verify everything before sending or acting on it. Avoid entering confidential or personal data.
        </p>
      </main>
    </div>
  );
}

const field = "w-full rounded-md border border-input bg-input/30 px-3 py-2 text-sm outline-none focus:border-ring";
const label = "mb-1 block text-xs font-medium uppercase tracking-wider text-muted-foreground";

function useRun() {
  const [out, setOut] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const run = async (system: string, user: string) => {
    setLoading(true);
    setError("");
    try {
      setOut(await runAI(system, user));
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setLoading(false);
    }
  };
  return { out, setOut, loading, error, run };
}

function Output({ r }: { r: ReturnType<typeof useRun> }) {
  const [copied, setCopied] = useState(false);
  if (r.loading)
    return (
      <div className="mt-6 flex items-center gap-3 rounded-md border border-border bg-card p-5 text-sm text-muted-foreground">
        <span className="h-4 w-4 animate-spin rounded-full border-2 border-gold border-t-transparent" /> Generating a response from your input…
      </div>
    );
  if (r.error) return <p className="mt-6 rounded-md border border-destructive/50 bg-destructive/10 p-4 text-sm">{r.error}</p>;
  if (!r.out) return null;
  return (
    <div className="mt-6">
      <div className="mb-2 flex items-center justify-between">
        <span className={label}>Result (editable)</span>
        <button
          onClick={() => {
            navigator.clipboard.writeText(r.out);
            setCopied(true);
            setTimeout(() => setCopied(false), 1500);
          }}
          className="rounded-md border border-gold/50 px-3 py-1 text-xs text-gold hover:bg-gold/10"
        >
          {copied ? "Copied ✓" : "Copy"}
        </button>
      </div>
      <textarea value={r.out} onChange={(e) => r.setOut(e.target.value)} rows={16} className={`${field} bg-card font-mono leading-relaxed`} />
    </div>
  );
}

function Submit({ disabled, loading, children }: { disabled: boolean; loading: boolean; children: string }) {
  return (
    <button
      type="submit"
      disabled={disabled || loading}
      className="rounded-md bg-gradient-gold px-5 py-2.5 text-sm font-semibold text-primary-foreground shadow-gold transition-opacity hover:opacity-90 disabled:opacity-40"
    >
      {loading ? "Working…" : children}
    </button>
  );
}

function EmailTool() {
  const r = useRun();
  const [f, setF] = useState({ recipient: "", sender: "", purpose: "", details: "", tone: "Formal" });
  const set = (k: keyof typeof f) => (e: React.ChangeEvent<HTMLInputElement | HTMLTextAreaElement>) => setF({ ...f, [k]: e.target.value });
  return (
    <form
      onSubmit={(e) => {
        e.preventDefault();
        r.run(
          "You are an expert business writer. Write one complete professional email. Use ONLY the facts provided; never invent names, dates or figures — if something is missing, use a clear [placeholder]. Output format: first line 'Subject: ...', blank line, then the email body with greeting and sign-off. No commentary.",
          `TONE: ${f.tone} (Formal = polished and respectful; Friendly = warm and conversational; Persuasive = benefit-focused with a clear call to action)\nRECIPIENT: ${f.recipient || "[recipient]"}\nSENDER: ${f.sender || "[your name]"}\nPURPOSE: ${f.purpose}\nKEY DETAILS:\n${f.details || "(none)"}`,
        );
      }}
      className="space-y-4"
    >
      <div className="grid gap-4 sm:grid-cols-2">
        <div><label className={label}>Recipient</label><input className={field} value={f.recipient} onChange={set("recipient")} placeholder="e.g. Thabo, Head of Finance" /></div>
        <div><label className={label}>Your name / role</label><input className={field} value={f.sender} onChange={set("sender")} placeholder="e.g. Nonhlanhla, Project Lead" /></div>
      </div>
      <div><label className={label}>Purpose *</label><input className={field} value={f.purpose} onChange={set("purpose")} placeholder="e.g. Request budget approval for Q1 training" /></div>
      <div><label className={label}>Key details</label><textarea rows={4} className={field} value={f.details} onChange={set("details")} placeholder="Facts, numbers, dates, context to include" /></div>
      <div>
        <label className={label}>Tone</label>
        <div className="flex flex-wrap gap-2">
          {["Formal", "Friendly", "Persuasive"].map((t) => (
            <button type="button" key={t} onClick={() => setF({ ...f, tone: t })}
              className={`rounded-full border px-4 py-1.5 text-sm ${f.tone === t ? "border-gold bg-gold/10 text-gold" : "border-border text-muted-foreground"}`}>
              {t}
            </button>
          ))}
        </div>
      </div>
      <Submit disabled={!f.purpose.trim()} loading={r.loading}>Generate email</Submit>
      <Output r={r} />
    </form>
  );
}

function NotesTool() {
  const r = useRun();
  const [notes, setNotes] = useState("");
  return (
    <form
      onSubmit={(e) => {
        e.preventDefault();
        r.run(
          "You summarise meeting notes accurately. Use ONLY information in the notes; never invent people, decisions or dates. If a section has nothing, write 'None identified'. Output plain text with these headings exactly:\nSUMMARY (3-5 sentences)\nKEY DECISIONS (bullets)\nACTION ITEMS (bullets: task — owner — due date, use 'Unassigned'/'No date' if missing)\nDEADLINES (bullets, chronological)\nOPEN QUESTIONS (bullets)",
          `MEETING NOTES:\n"""\n${notes}\n"""`,
        );
      }}
      className="space-y-4"
    >
      <div><label className={label}>Meeting notes *</label><textarea rows={10} className={field} value={notes} onChange={(e) => setNotes(e.target.value)} placeholder="Paste your raw notes or transcript here…" /></div>
      <Submit disabled={notes.trim().length < 20} loading={r.loading}>Summarise notes</Submit>
      <Output r={r} />
    </form>
  );
}

function PlannerTool() {
  const r = useRun();
  const [f, setF] = useState({ tasks: "", period: "Daily", hours: "08:00–17:00", notes: "" });
  const set = (k: keyof typeof f) => (e: React.ChangeEvent<HTMLInputElement | HTMLTextAreaElement>) => setF({ ...f, [k]: e.target.value });
  return (
    <form
      onSubmit={(e) => {
        e.preventDefault();
        const today = new Date().toDateString();
        r.run(
          "You are a productivity coach. Build a realistic schedule using ONLY the user's tasks. Prioritise by urgency and deadline (Eisenhower: urgent+important first), include short breaks, and respect working hours and constraints. Output plain text with headings:\nPRIORITY RANKING (numbered, with one-line reason each)\nSCHEDULE (time blocks; for weekly, group by day)\nTIPS (2-3 short, specific to these tasks)",
          `TODAY: ${today}\nPLAN TYPE: ${f.period}\nWORKING HOURS: ${f.hours}\nTASKS (with deadlines/estimates if given):\n${f.tasks}\nCONSTRAINTS / PREFERENCES: ${f.notes || "(none)"}`,
        );
      }}
      className="space-y-4"
    >
      <div><label className={label}>Tasks *</label><textarea rows={6} className={field} value={f.tasks} onChange={set("tasks")} placeholder={"One per line, e.g.\nFinish client report — due Friday — 3h\nTeam stand-up — daily 9am"} /></div>
      <div className="grid gap-4 sm:grid-cols-2">
        <div>
          <label className={label}>Plan type</label>
          <div className="flex gap-2">
            {["Daily", "Weekly"].map((p) => (
              <button type="button" key={p} onClick={() => setF({ ...f, period: p })}
                className={`rounded-full border px-4 py-1.5 text-sm ${f.period === p ? "border-gold bg-gold/10 text-gold" : "border-border text-muted-foreground"}`}>{p}</button>
            ))}
          </div>
        </div>
        <div><label className={label}>Working hours</label><input className={field} value={f.hours} onChange={set("hours")} /></div>
      </div>
      <div><label className={label}>Constraints / preferences</label><input className={field} value={f.notes} onChange={set("notes")} placeholder="e.g. Deep work in mornings, gym at 17:30" /></div>
      <Submit disabled={!f.tasks.trim()} loading={r.loading}>Build my plan</Submit>
      <Output r={r} />
    </form>
  );
}
